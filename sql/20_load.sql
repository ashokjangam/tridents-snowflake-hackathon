-- Load local Synthea CSVs and the parsed C-CDA section CSV.
-- Snowflake CLI executes PUT. The warehouse executes DELETE and COPY.
-- __DATA_ROOT_URI__ and __GENERATED_URI__ are expanded by
-- scripts/Invoke-Patient360Load.ps1 into local file URIs.
-- Do not run this template directly while those tokens remain.
-- Re-run is safe: REMOVE, PUT OVERWRITE, DELETE, COPY FORCE = TRUE.
-- DELETE is used instead of TRUNCATE so PATIENT_360_LOADER can reload without ownership.
-- Each table is one transaction. A failed COPY rolls back that table's DELETE.
-- PUT and REMOVE are client operations and sit outside the transaction.
-- The 18 clinical files load first. The parsed document file is a separate block.
-- The parser writes patient-360/generated/document_section.csv before that block.
-- Its 26-column header is generated by scripts/parse_ccda.py and includes
-- citation, reconciliation, and quote-safety fields.
-- element_id is the C-CDA XML ID. section_loinc is the section code.
-- Description cells use ids such as medications-desc-2. Code cells use medications-code-2.
-- CODE holds the code token when the cell has one. TEXT is the narrative cell text.
-- Quote fields. Doubled quotes are the escape. Do not put credentials in the file.
-- Timestamps use the digits in the file. The trailing Z is a format marker, not a conversion.

USE DATABASE PATIENT_360;
USE SCHEMA RAW;
USE WAREHOUSE PATIENT_360_WH;

SET PATIENT_360_LOAD_BATCH_ID = (
    SELECT TO_VARCHAR(CURRENT_TIMESTAMP(0), 'YYYYMMDDHH24MISS')
        || '-' || REPLACE(UUID_STRING(), '-', '')
);

