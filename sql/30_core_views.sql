WHERE IMAGING_TS < TIMESTAMP '2023-01-01 00:00:00'
UNION ALL
SELECT
    'SUPPLY',
    PATIENT_ID,
    ENCOUNTER_ID,
    CODE,
    DESCRIPTION,
    TO_TIMESTAMP_NTZ(SUPPLY_DATE),
    CAST(NULL AS VARCHAR),
    CAST(NULL AS BOOLEAN),
    CAST(NULL AS VARCHAR),
    SOURCE_FILE_ROW_NUMBER
FROM PATIENT_360.CORE.SUPPLY
WHERE SUPPLY_DATE < DATE '2023-01-01';

CREATE OR REPLACE VIEW PATIENT_360.CORE.RISK_COHORT
COPY GRANTS
COMMENT = 'Frozen point count for patients born before 2023-01-01, alive at that date, with an encounter before that date. Points: age >= 65; prior emergency or inpatient encounter; at least 8 conditions still active; last prior Hemoglobin A1c code 4548-4 >= 6.5. EVENT_FLAG is an emergency or inpatient encounter in 2023. Point count, not a probability and not a care recommendation. Points are not retuned.'
AS
WITH eligible AS (
    SELECT
        p.PATIENT_ID,
        p.BIRTHDATE,
        DATEDIFF('year', p.BIRTHDATE, DATE '2023-01-01')
            - IFF(
                DATEADD(
                    'year',
                    DATEDIFF('year', p.BIRTHDATE, DATE '2023-01-01'),
                    p.BIRTHDATE
                ) > DATE '2023-01-01',
                1,
                0
            ) AS AGE_YEARS_AT_INDEX
    FROM PATIENT_360.CORE.PATIENT AS p
    WHERE p.BIRTHDATE < DATE '2023-01-01'
        AND (p.DEATHDATE IS NULL OR p.DEATHDATE > DATE '2023-01-01')
        AND EXISTS (
            SELECT 1
            FROM PATIENT_360.CORE.RISK_FEATURE AS f
            WHERE f.SOURCE_TABLE = 'ENCOUNTER'
                AND f.PATIENT_ID = p.PATIENT_ID
        )
),
prior_acute AS (
    SELECT DISTINCT PATIENT_ID
    FROM PATIENT_360.CORE.RISK_FEATURE
    WHERE SOURCE_TABLE = 'ENCOUNTER'
        AND EVENT_CLASS IN ('emergency', 'inpatient')
),
active_conditions AS (
    SELECT
        PATIENT_ID,
        COUNT(*) AS ACTIVE_CONDITION_COUNT
    FROM PATIENT_360.CORE.RISK_FEATURE
    WHERE SOURCE_TABLE = 'CONDITION'
        AND ACTIVE_AT_INDEX = TRUE
    GROUP BY PATIENT_ID
),
last_a1c AS (
    SELECT
        PATIENT_ID,
        TRY_TO_NUMBER(VALUE_TEXT, 18, 4) AS LAST_A1C_VALUE
    FROM PATIENT_360.CORE.RISK_FEATURE
    WHERE SOURCE_TABLE = 'OBSERVATION'
        AND CODE = '4548-4'
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY PATIENT_ID
        ORDER BY EVENT_TS DESC, SOURCE_FILE_ROW_NUMBER DESC
    ) = 1
),
scored AS (
    SELECT
        e.PATIENT_ID,
        e.BIRTHDATE,
        e.AGE_YEARS_AT_INDEX,
        IFF(e.AGE_YEARS_AT_INDEX >= 65, 1, 0) AS POINT_AGE_GE_65,
        IFF(a.PATIENT_ID IS NOT NULL, 1, 0) AS POINT_PRIOR_ACUTE_ENCOUNTER,
        COALESCE(c.ACTIVE_CONDITION_COUNT, 0) AS ACTIVE_CONDITION_COUNT,
        IFF(COALESCE(c.ACTIVE_CONDITION_COUNT, 0) >= 8, 1, 0) AS POINT_ACTIVE_CONDITIONS_GE_8,
        h.LAST_A1C_VALUE,
        IFF(COALESCE(h.LAST_A1C_VALUE >= 6.5, FALSE), 1, 0) AS POINT_LAST_A1C_GE_6_5,
        IFF(
            EXISTS (
                SELECT 1
                FROM PATIENT_360.CORE.ENCOUNTER AS enc
                WHERE enc.PATIENT_ID = e.PATIENT_ID
                    AND enc.ENCOUNTER_CLASS IN ('emergency', 'inpatient')
                    AND enc.START_TS >= TIMESTAMP '2023-01-01 00:00:00'
                    AND enc.START_TS < TIMESTAMP '2024-01-01 00:00:00'
            ),
            1,
            0
        ) AS EVENT_FLAG
    FROM eligible AS e
    LEFT JOIN prior_acute AS a
        ON a.PATIENT_ID = e.PATIENT_ID
    LEFT JOIN active_conditions AS c
        ON c.PATIENT_ID = e.PATIENT_ID
    LEFT JOIN last_a1c AS h
        ON h.PATIENT_ID = e.PATIENT_ID
)
SELECT
    PATIENT_ID,
    BIRTHDATE,
    AGE_YEARS_AT_INDEX,
    POINT_AGE_GE_65,
    POINT_PRIOR_ACUTE_ENCOUNTER,
    ACTIVE_CONDITION_COUNT,
    POINT_ACTIVE_CONDITIONS_GE_8,
    LAST_A1C_VALUE,
    POINT_LAST_A1C_GE_6_5,
    POINT_AGE_GE_65
        + POINT_PRIOR_ACUTE_ENCOUNTER
        + POINT_ACTIVE_CONDITIONS_GE_8
        + POINT_LAST_A1C_GE_6_5 AS POINT_TOTAL,
    EVENT_FLAG,
    DATE '2023-01-01' AS INDEX_DATE,
    DATE '2024-01-01' AS HORIZON_END
FROM scored;

CREATE OR REPLACE VIEW PATIENT_360.CORE.RISK_SCORE
COPY GRANTS
COMMENT = 'Bucket table for the frozen point count. Cohort 97 and 14 horizon events are measured, not targets to fit. Score 2 sits below score 1. Point count, not a validated stratifier and not a care recommendation. Condition counts include findings, disorders, and situations.'
AS
WITH scores AS (
    SELECT 0 AS SCORE_VALUE
    UNION ALL SELECT 1
    UNION ALL SELECT 2
    UNION ALL SELECT 3
    UNION ALL SELECT 4
),
totals AS (
    SELECT
        COUNT(*) AS COHORT_PATIENT_COUNT,
        COALESCE(SUM(EVENT_FLAG), 0) AS COHORT_EVENT_COUNT
    FROM PATIENT_360.CORE.RISK_COHORT
),
exclusions AS (
    SELECT
        (
            SELECT COUNT(*)
            FROM PATIENT_360.CORE.PATIENT
            WHERE BIRTHDATE >= DATE '2023-01-01'
        ) AS EXCLUDED_BORN_ON_OR_AFTER_INDEX,
        (
            SELECT COUNT(*)
            FROM PATIENT_360.CORE.PATIENT
            WHERE BIRTHDATE < DATE '2023-01-01'
                AND DEATHDATE IS NOT NULL
                AND DEATHDATE <= DATE '2023-01-01'
        ) AS EXCLUDED_DEAD_ON_OR_BEFORE_INDEX,
        (
            SELECT COUNT(*)
            FROM PATIENT_360.CORE.PATIENT AS p
            WHERE p.BIRTHDATE < DATE '2023-01-01'
                AND (p.DEATHDATE IS NULL OR p.DEATHDATE > DATE '2023-01-01')
                AND NOT EXISTS (
                    SELECT 1
                    FROM PATIENT_360.CORE.ENCOUNTER AS e
                    WHERE e.PATIENT_ID = p.PATIENT_ID
                        AND e.START_TS < TIMESTAMP '2023-01-01 00:00:00'
                )
        ) AS EXCLUDED_NO_PRIOR_ENCOUNTER
),
buckets AS (
    SELECT
        TO_VARCHAR(s.SCORE_VALUE) AS SCORE_BUCKET,
        s.SCORE_VALUE AS SORT_ORDER,
        COUNT(c.PATIENT_ID) AS PATIENT_COUNT,
        COALESCE(SUM(c.EVENT_FLAG), 0) AS EVENT_COUNT
    FROM scores AS s
    LEFT JOIN PATIENT_360.CORE.RISK_COHORT AS c
        ON c.POINT_TOTAL = s.SCORE_VALUE
    GROUP BY s.SCORE_VALUE
),
ge2 AS (
    SELECT
        'GE_2' AS SCORE_BUCKET,
        5 AS SORT_ORDER,
        COUNT(*) AS PATIENT_COUNT,
        COALESCE(SUM(EVENT_FLAG), 0) AS EVENT_COUNT
    FROM PATIENT_360.CORE.RISK_COHORT
    WHERE POINT_TOTAL >= 2
)
SELECT
    b.SCORE_BUCKET,
    b.SORT_ORDER,
    b.PATIENT_COUNT,
    b.EVENT_COUNT,
    ROUND(100.0 * b.EVENT_COUNT / NULLIF(b.PATIENT_COUNT, 0), 2) AS EVENT_RATE_PCT,
    t.COHORT_PATIENT_COUNT,
    t.COHORT_EVENT_COUNT,
    ROUND(100.0 * t.COHORT_EVENT_COUNT / NULLIF(t.COHORT_PATIENT_COUNT, 0), 2) AS BASE_RATE_PCT,
    x.EXCLUDED_BORN_ON_OR_AFTER_INDEX,
    x.EXCLUDED_DEAD_ON_OR_BEFORE_INDEX,
    x.EXCLUDED_NO_PRIOR_ENCOUNTER,
    'Point count, not a validated stratifier and not a care recommendation. Score 2 sits below score 1 on this extract.' AS SCORE_STATEMENT
FROM (
    SELECT * FROM buckets
    UNION ALL
    SELECT * FROM ge2
) AS b
CROSS JOIN totals AS t
CROSS JOIN exclusions AS x;
