CREATE OR REPLACE VIEW PATIENT_360.CORE.MEMBER_SUMMARY
COPY GRANTS
COMMENT = 'One row per simulated patient. Counts are chart, claim, coverage, and document facts. Not a risk score.'
AS
SELECT
    p.PATIENT_ID,
    p.FIRST_NAME,
    p.LAST_NAME,
    p.BIRTHDATE,
    p.DEATHDATE,
    p.GENDER,
    p.CITY,
    p.STATE,
    COALESCE(e.ENCOUNTER_COUNT, 0) AS ENCOUNTER_COUNT,
    e.LAST_ENCOUNTER_TS,
    COALESCE(c.CLAIM_COUNT, 0) AS CLAIM_COUNT,
    COALESCE(m.MEDICATION_COUNT, 0) AS MEDICATION_COUNT,
    COALESCE(k.CONDITION_COUNT, 0) AS CONDITION_COUNT,
    COALESCE(o.OBSERVATION_COUNT, 0) AS OBSERVATION_COUNT,
    COALESCE(a.ALLERGY_COUNT, 0) AS ALLERGY_COUNT,
    COALESCE(s.COVERAGE_SPAN_COUNT, 0) AS COVERAGE_SPAN_COUNT,
    COALESCE(s.COVERAGE_SPAN_WITH_MEMBER_ID_COUNT, 0) AS COVERAGE_SPAN_WITH_MEMBER_ID_COUNT,
    COALESCE(d.DOCUMENT_COUNT, 0) AS DOCUMENT_COUNT
FROM PATIENT_360.CORE.PATIENT AS p
LEFT JOIN (
    SELECT
        PATIENT_ID,
        COUNT(*) AS ENCOUNTER_COUNT,
        MAX(START_TS) AS LAST_ENCOUNTER_TS
    FROM PATIENT_360.CORE.ENCOUNTER
    GROUP BY PATIENT_ID
) AS e
    ON e.PATIENT_ID = p.PATIENT_ID
LEFT JOIN (
    SELECT PATIENT_ID, COUNT(*) AS CLAIM_COUNT
    FROM PATIENT_360.CORE.CLAIM
    GROUP BY PATIENT_ID
) AS c
    ON c.PATIENT_ID = p.PATIENT_ID
LEFT JOIN (
    SELECT PATIENT_ID, COUNT(*) AS MEDICATION_COUNT
    FROM PATIENT_360.CORE.MEDICATION
    GROUP BY PATIENT_ID
) AS m
    ON m.PATIENT_ID = p.PATIENT_ID
LEFT JOIN (
    SELECT PATIENT_ID, COUNT(*) AS CONDITION_COUNT
    FROM PATIENT_360.CORE.CONDITION
    GROUP BY PATIENT_ID
) AS k
    ON k.PATIENT_ID = p.PATIENT_ID
LEFT JOIN (
    SELECT PATIENT_ID, COUNT(*) AS OBSERVATION_COUNT
    FROM PATIENT_360.CORE.OBSERVATION
    GROUP BY PATIENT_ID
) AS o
    ON o.PATIENT_ID = p.PATIENT_ID
LEFT JOIN (
    SELECT PATIENT_ID, COUNT(*) AS ALLERGY_COUNT
    FROM PATIENT_360.CORE.ALLERGY
    GROUP BY PATIENT_ID
) AS a
    ON a.PATIENT_ID = p.PATIENT_ID
LEFT JOIN (
    SELECT
        PATIENT_ID,
        COUNT(*) AS COVERAGE_SPAN_COUNT,
        COUNT(MEMBER_ID) AS COVERAGE_SPAN_WITH_MEMBER_ID_COUNT
    FROM PATIENT_360.CORE.PAYER_TRANSITION
    GROUP BY PATIENT_ID
) AS s
    ON s.PATIENT_ID = p.PATIENT_ID
LEFT JOIN (
    SELECT PATIENT_ID, COUNT(DISTINCT DOCUMENT_ID) AS DOCUMENT_COUNT
    FROM PATIENT_360.CORE.DOCUMENT_SECTION
    GROUP BY PATIENT_ID
) AS d
    ON d.PATIENT_ID = p.PATIENT_ID;

