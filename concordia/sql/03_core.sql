CREATE OR REPLACE FUNCTION CORE.PARSE_DATE(S VARCHAR)
RETURNS DATE
AS $$ COALESCE(TRY_TO_DATE(S, 'YYYY-MM-DD'), TRY_TO_DATE(S, 'MM/DD/YYYY'), TRY_TO_DATE(S, 'DD.MM.YYYY')) $$;

CREATE OR REPLACE FUNCTION CORE.MINOR(S VARCHAR)
RETURNS NUMBER(38,0)
AS $$ IFF(S IS NULL, NULL, ROUND(TO_NUMBER(S, 38, 2) * 100, 0)::NUMBER(38,0)) $$;

