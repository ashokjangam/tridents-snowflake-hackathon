-- Metric contract 1.0.0 in SQL. This file is the only numeric authority.
-- *_LINES / *_RECEIPTS / M4_FACILITY return contribution rows for one world and one RECORDED_AS_OF.
-- *_RESULT functions filter period and scope and aggregate with the same expressions the
-- publisher uses (the COUNT_AGG, FILL_AGG and LANDED_AGG templates from scripts/metric_sql.py).

USE ROLE CONCORDIA_ADMIN;
USE WAREHOUSE CONCORDIA_WH;
USE DATABASE CONCORDIA;

-- ---------------------------------------------------------------- M1 inbound supplier OTD
CREATE OR REPLACE FUNCTION CORE.M1_LINES(P_W VARCHAR, P_ASOF TIMESTAMP_TZ)
RETURNS TABLE (LINE_ID VARCHAR, PERIOD_DATE DATE, ITEM_ID VARCHAR, FACILITY_ID VARCHAR, SUPPLIER_ID VARCHAR, GEOGRAPHY_ID VARCHAR,
               CUSTOMER_ID VARCHAR, OUTCOME VARCHAR, REASONS ARRAY, QTY NUMBER(38,6), FILLED_QTY NUMBER(38,6),
               COMMITMENT_ON DATE, COMPLETED_ON DATE, DRIVER VARCHAR)
AS
$$
WITH l AS (
  SELECT * FROM CORE.PO_LINE WHERE WORLD_ID = P_W AND (VISIBLE_AT IS NULL OR VISIBLE_AT <= P_ASOF)
), acc AS (
  SELECT a.LINE_ID, a.ACCEPTED_ON, a.QTY,
         SUM(a.QTY) OVER (PARTITION BY a.LINE_ID ORDER BY a.ACCEPTED_ON, a.SEQ ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS RUNNING
  FROM CORE.PO_ACCEPTANCE a
  WHERE a.WORLD_ID = P_W AND a.VISIBLE_AT IS NOT NULL AND a.VISIBLE_AT <= P_ASOF
), done AS (
  SELECT l.LINE_ID, MIN(IFF(acc.RUNNING >= l.ORDERED_QTY, acc.ACCEPTED_ON, NULL)) AS COMPLETED, SUM(acc.QTY) AS ACCEPTED_TOTAL
  FROM l JOIN acc ON acc.LINE_ID = l.LINE_ID GROUP BY l.LINE_ID
), x AS (
  SELECT l.*, gc.CALENDAR_ID IS NOT NULL AS HAS_CAL, dl.DAY AS DEADLINE, done.COMPLETED, COALESCE(done.ACCEPTED_TOTAL, 0) AS ACCEPTED_TOTAL
  FROM l
  LEFT JOIN done ON done.LINE_ID = l.LINE_ID
  LEFT JOIN GOV.CALENDAR gc ON gc.CALENDAR_ID = l.CALENDAR_ID
  LEFT JOIN GOV.CALENDAR_DAY c1 ON c1.CALENDAR_ID = l.CALENDAR_ID AND c1.DAY = l.ISSUED_ON
  LEFT JOIN GOV.CALENDAR_DAY dl ON dl.CALENDAR_ID = l.CALENDAR_ID AND dl.IS_BUSINESS AND dl.BUSINESS_ORDINAL = c1.BUSINESS_ORDINAL + 2
), y AS (
  SELECT x.*,
         ARRAY_CONSTRUCT_COMPACT(
           IFF(IDENTITY_RESOLVED = FALSE, 'IDENTITY_UNRESOLVED', NULL),
           IFF(UOM_RESOLVED = FALSE, 'UOM_UNRESOLVED', NULL),
           IFF(TIMEZONE_RESOLVED = FALSE OR TIMEZONE IS NULL OR TIMEZONE = '', 'TIMEZONE_MISSING', NULL),
           IFF(NOT HAS_CAL, 'CALENDAR_MISSING', NULL),
           IFF(DISPOSITION_MISSING = TRUE, 'DISPOSITION_MISSING', NULL),
           IFF(CANCELLATION = 'BUYER_BEFORE_COMMITMENT', 'BUYER_CANCELLED', NULL)) AS FLAGS,
         IFF(HAS_CAL AND ACK_ON IS NOT NULL AND ACK_PROMISE_ON IS NOT NULL AND ACK_VISIBLE_AT IS NOT NULL AND ACK_VISIBLE_AT <= P_ASOF
             AND ACK_ON <= DEADLINE AND NOT (FIRST_RECEIPT_ON IS NOT NULL AND ACK_ON > FIRST_RECEIPT_ON),
             ACK_PROMISE_ON, BUYER_REQUESTED_ON) AS COMMITMENT
  FROM x
)
SELECT LINE_ID, COMMITMENT, ITEM_ID, FACILITY_ID, SUPPLIER_ID, NULL, NULL,
       CASE
         WHEN ARRAY_SIZE(FLAGS) > 0 THEN 'EXCLUDED'
         WHEN CANCELLATION = 'SUPPLIER_LATE' AND COMPLETED IS NULL THEN 'MISS'
         WHEN COMPLETED IS NULL AND COMMITMENT > CONVERT_TIMEZONE(TIMEZONE, P_ASOF)::DATE THEN 'EXCLUDED'
         WHEN COMPLETED IS NOT NULL AND COMPLETED <= COMMITMENT THEN 'HIT'
         ELSE 'MISS' END,
       CASE
         WHEN ARRAY_SIZE(FLAGS) > 0 THEN FLAGS
         WHEN CANCELLATION = 'SUPPLIER_LATE' AND COMPLETED IS NULL THEN ARRAY_CONSTRUCT()
         WHEN COMPLETED IS NULL AND COMMITMENT > CONVERT_TIMEZONE(TIMEZONE, P_ASOF)::DATE THEN ARRAY_CONSTRUCT('FUTURE_OPEN')
         ELSE ARRAY_CONSTRUCT() END,
       IFF(ARRAY_SIZE(FLAGS) > 0, COALESCE(ORDERED_QTY, 0), ORDERED_QTY),
       NULL,
       COMMITMENT, COMPLETED,
       CASE
         WHEN ARRAY_SIZE(FLAGS) > 0 OR (COMPLETED IS NOT NULL AND COMPLETED <= COMMITMENT) THEN NULL
         WHEN COMPLETED IS NULL AND CANCELLATION IS NULL AND COMMITMENT > CONVERT_TIMEZONE(TIMEZONE, P_ASOF)::DATE THEN NULL
         WHEN CANCELLATION = 'SUPPLIER_LATE' THEN 'SUPPLIER_CANCELLED'
         WHEN COALESCE(SUPPLIER_REJECTED_QTY, 0) > 0 THEN 'SUPPLIER_REJECT'
         WHEN COMPLETED IS NULL AND ACCEPTED_TOTAL > 0 THEN 'PARTIAL_RECEIPT'
         WHEN COMPLETED IS NULL THEN 'OPEN_PAST_DUE'
         ELSE 'LATE_RECEIPT' END
FROM y
$$;

-- ---------------------------------------------------------------- M2 outbound customer OTD
CREATE OR REPLACE FUNCTION CORE.M2_LINES(P_W VARCHAR, P_ASOF TIMESTAMP_TZ)
RETURNS TABLE (LINE_ID VARCHAR, PERIOD_DATE DATE, ITEM_ID VARCHAR, FACILITY_ID VARCHAR, SUPPLIER_ID VARCHAR, GEOGRAPHY_ID VARCHAR,
               CUSTOMER_ID VARCHAR, OUTCOME VARCHAR, REASONS ARRAY, QTY NUMBER(38,6), FILLED_QTY NUMBER(38,6),
               COMMITMENT_ON DATE, COMPLETED_ON DATE, DRIVER VARCHAR)
AS
$$
WITH l AS (
  SELECT s.*, gc.CALENDAR_ID IS NOT NULL AS HAS_CAL,
         IFF(s.SHORT_CLOSE_QTY IS NOT NULL AND s.SHORT_CLOSE_APPROVED_ON IS NOT NULL AND s.SHORT_CLOSE_APPROVED_ON <= s.ORIGINAL_PROMISE_ON,
             s.SHORT_CLOSE_QTY, s.ORDERED_QTY) AS REQUIRED,
         IFF(s.INCOTERM IN ('EXW', 'FCA'), 'READY', 'POD') AS MILESTONE
  FROM CORE.SO_LINE s LEFT JOIN GOV.CALENDAR gc ON gc.CALENDAR_ID = s.CALENDAR_ID
  WHERE s.WORLD_ID = P_W AND (s.VISIBLE_AT IS NULL OR s.VISIBLE_AT <= P_ASOF)
), ev AS (
  SELECT e.LINE_ID, e.KIND, e.EVENT_ON, e.QTY, e.SEQ
  FROM CORE.SO_DELIVERY_EVENT e
  WHERE e.WORLD_ID = P_W AND e.VISIBLE_AT IS NOT NULL AND e.VISIBLE_AT <= P_ASOF
), counted AS (
  SELECT ev.LINE_ID, ev.EVENT_ON, ev.QTY, l.REQUIRED,
         SUM(ev.QTY) OVER (PARTITION BY ev.LINE_ID ORDER BY ev.EVENT_ON, ev.SEQ ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS RUNNING
  FROM ev JOIN l ON l.LINE_ID = ev.LINE_ID AND ev.KIND = l.MILESTONE
), done AS (
  SELECT LINE_ID, MIN(IFF(RUNNING >= REQUIRED, EVENT_ON, NULL)) AS COMPLETED, COUNT(*) AS COUNTED_EVENTS FROM counted GROUP BY LINE_ID
), failed AS (
  SELECT LINE_ID, COUNT(*) AS FAILED_ATTEMPTS FROM ev WHERE KIND IN ('ATTEMPT', 'MISDELIVERY') GROUP BY LINE_ID
), revised AS (
  SELECT LINE_ID, COUNT(*) AS REVISIONS FROM CORE.PROMISE_REVISION
  WHERE WORLD_ID = P_W AND KIND = 'REVISED' AND (VISIBLE_AT IS NULL OR VISIBLE_AT <= P_ASOF) GROUP BY LINE_ID
), x AS (
  SELECT l.*,
         ARRAY_CONSTRUCT_COMPACT(
           IFF(IDENTITY_RESOLVED = FALSE, 'IDENTITY_UNRESOLVED', NULL),
           IFF(UOM_RESOLVED = FALSE, 'UOM_UNRESOLVED', NULL),
           IFF(TIMEZONE IS NULL OR TIMEZONE = '', 'TIMEZONE_MISSING', NULL),
           IFF(NOT HAS_CAL, 'CALENDAR_MISSING', NULL),
           IFF(INCOTERM IS NULL OR INCOTERM = '', 'INCOTERM_MISSING', NULL),
           IFF(INCOTERM IS NOT NULL AND INCOTERM <> '' AND INCOTERM NOT IN ('EXW', 'FCA', 'DAP', 'DDP'), 'INCOTERM_UNSUPPORTED', NULL)) AS FLAGS,
         HOLD_START IS NOT NULL AND HOLD_END IS NOT NULL AND HOLD_RECORDED_ON IS NOT NULL AND HOLD_RECORDED_ON <= ORIGINAL_PROMISE_ON
           AND HOLD_START <= ORIGINAL_PROMISE_ON AND ORIGINAL_PROMISE_ON <= HOLD_END AS HOLD_EXCLUDES,
         done.COMPLETED, COALESCE(failed.FAILED_ATTEMPTS, 0) AS FAILED_ATTEMPTS, COALESCE(done.COUNTED_EVENTS, 0) AS COUNTED_EVENTS,
         COALESCE(revised.REVISIONS, 0) AS REVISIONS
  FROM l
  LEFT JOIN done ON done.LINE_ID = l.LINE_ID
  LEFT JOIN failed ON failed.LINE_ID = l.LINE_ID
  LEFT JOIN revised ON revised.LINE_ID = l.LINE_ID
), y AS (
  SELECT x.*,
         CASE
           WHEN ARRAY_SIZE(FLAGS) > 0 THEN 'EXCLUDED'
           WHEN CANCELLATION = 'CUSTOMER_BEFORE_PICK' THEN 'EXCLUDED'
           WHEN HOLD_EXCLUDES THEN 'EXCLUDED'
           WHEN COMPLETED IS NULL AND ORIGINAL_PROMISE_ON > CONVERT_TIMEZONE(TIMEZONE, P_ASOF)::DATE THEN 'EXCLUDED'
           WHEN COMPLETED IS NOT NULL AND COMPLETED <= ORIGINAL_PROMISE_ON THEN 'HIT'
           ELSE 'MISS' END AS OUTCOME
  FROM x
)
SELECT LINE_ID, ORIGINAL_PROMISE_ON, ITEM_ID, FACILITY_ID, NULL, GEOGRAPHY_ID, CUSTOMER_ID, OUTCOME,
       CASE
         WHEN ARRAY_SIZE(FLAGS) > 0 THEN FLAGS
         WHEN CANCELLATION = 'CUSTOMER_BEFORE_PICK' THEN ARRAY_CONSTRUCT('CUSTOMER_CANCELLED')
         WHEN HOLD_EXCLUDES THEN ARRAY_CONSTRUCT('CUSTOMER_HOLD')
         WHEN OUTCOME = 'EXCLUDED' THEN ARRAY_CONSTRUCT('FUTURE_OPEN')
         ELSE ARRAY_CONSTRUCT() END,
       IFF(ARRAY_SIZE(FLAGS) > 0 OR CANCELLATION = 'CUSTOMER_BEFORE_PICK' OR HOLD_EXCLUDES, COALESCE(ORDERED_QTY, 0), REQUIRED),
       NULL, ORIGINAL_PROMISE_ON, COMPLETED,
       IFF(OUTCOME <> 'MISS', NULL,
         CASE
           WHEN FAILED_ATTEMPTS > 0 THEN 'FAILED_OR_MISDELIVERED'
           WHEN COUNTED_EVENTS > 1 THEN 'PARTIAL_DELIVERY'
           WHEN REVISIONS > 0 THEN 'PROMISE_REVISED'
           WHEN COMPLETED IS NOT NULL THEN 'LATE_DELIVERY'
           WHEN CANCELLATION = 'COMPANY' THEN 'COMPANY_CANCELLED'
           ELSE 'NOT_DELIVERED' END)
FROM y
$$;

-- ---------------------------------------------------------------- M3 unit fill rate
CREATE OR REPLACE FUNCTION CORE.M3_LINES(P_W VARCHAR, P_ASOF TIMESTAMP_TZ)
RETURNS TABLE (LINE_ID VARCHAR, PERIOD_DATE DATE, ITEM_ID VARCHAR, FACILITY_ID VARCHAR, SUPPLIER_ID VARCHAR, GEOGRAPHY_ID VARCHAR,
               CUSTOMER_ID VARCHAR, OUTCOME VARCHAR, REASONS ARRAY, QTY NUMBER(38,6), FILLED_QTY NUMBER(38,6),
               COMMITMENT_ON DATE, COMPLETED_ON DATE, DRIVER VARCHAR)
AS
$$
WITH shipped AS (
  SELECT LINE_ID, SUM(QTY) AS QTY FROM CORE.SO_SHIPMENT
  WHERE WORLD_ID = P_W AND VISIBLE_AT IS NOT NULL AND VISIBLE_AT <= P_ASOF GROUP BY LINE_ID
), l AS (
  SELECT s.*, COALESCE(shipped.QTY, 0) AS SHIPPED_VISIBLE
  FROM CORE.SO_LINE s LEFT JOIN shipped ON shipped.LINE_ID = s.LINE_ID
  WHERE s.WORLD_ID = P_W AND (s.VISIBLE_AT IS NULL OR s.VISIBLE_AT <= P_ASOF)
), x AS (
  SELECT l.*,
         CASE
           WHEN UOM_RESOLVED = FALSE OR ORDERED_QTY IS NULL THEN 'UOM_UNRESOLVED'
           WHEN CANCELLATION = 'CUSTOMER_BEFORE_PICK' THEN 'CUSTOMER_CANCELLED' END AS EXCLUSION,
         LEAST(IFF(CANCELLATION = 'COMPANY' OR SUBSTITUTE = 'SILENT', 0, SHIPPED_VISIBLE), ORDERED_QTY) AS CAPPED
  FROM l
)
SELECT LINE_ID, REQUESTED_SHIP_ON, ITEM_ID, FACILITY_ID, NULL, GEOGRAPHY_ID, CUSTOMER_ID,
       CASE WHEN EXCLUSION IS NOT NULL THEN 'EXCLUDED' WHEN CAPPED < ORDERED_QTY THEN 'MISS' ELSE 'HIT' END,
       IFF(EXCLUSION IS NOT NULL, ARRAY_CONSTRUCT(EXCLUSION), ARRAY_CONSTRUCT()),
       ORDERED_QTY, IFF(EXCLUSION IS NOT NULL, NULL, CAPPED), REQUESTED_SHIP_ON, NULL,
       CASE
         WHEN EXCLUSION IS NOT NULL OR CAPPED >= ORDERED_QTY THEN NULL
         WHEN CANCELLATION = 'COMPANY' THEN 'COMPANY_CANCELLED'
         WHEN SUBSTITUTE = 'SILENT' THEN 'SILENT_SUBSTITUTE'
         WHEN CAPPED > 0 THEN 'PARTIAL_SHIPMENT'
         ELSE 'NOT_SHIPPED' END
FROM x
$$;

-- ---------------------------------------------------------------- aggregates for line metrics
CREATE OR REPLACE FUNCTION CORE.COUNT_RESULT_M1(P_W VARCHAR, P_PS DATE, P_PE DATE, P_ASOF TIMESTAMP_TZ, P_ITEM VARCHAR, P_FACILITY VARCHAR,
                                                P_GEO VARCHAR, P_SUPPLIER VARCHAR, P_CUSTOMER VARCHAR)
RETURNS TABLE (STATUS VARCHAR, NUMERATOR VARCHAR, DENOMINATOR VARCHAR, DISPLAY VARCHAR, VALUE_NUM NUMBER(38,12), REASONS ARRAY, COVERAGE VARCHAR,
               DIAGNOSTIC_DISPLAY VARCHAR, EXCLUDED_COUNT NUMBER, AFFECTED_COMMITMENTS NUMBER, AFFECTED_UNITS VARCHAR, UNRESOLVED_RECORDS NUMBER,
               EVIDENCE_IDS ARRAY)
AS
$$
SELECT {{COUNT_AGG}}
FROM TABLE(CORE.M1_LINES(P_W, P_ASOF))
WHERE PERIOD_DATE BETWEEN P_PS AND P_PE
  AND (P_ITEM IS NULL OR ITEM_ID = P_ITEM) AND (P_FACILITY IS NULL OR FACILITY_ID = P_FACILITY)
  AND (P_GEO IS NULL OR GEOGRAPHY_ID = P_GEO) AND (P_SUPPLIER IS NULL OR SUPPLIER_ID = P_SUPPLIER) AND (P_CUSTOMER IS NULL OR CUSTOMER_ID = P_CUSTOMER)
$$;

